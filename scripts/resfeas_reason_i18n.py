# Fallback used when the disease field is empty, in both languages.
DISEASE_UNKNOWN: dict[str, str] = {"zh": "未标注", "en": "not annotated"}

# How the individual reasons are joined. Identical in both languages on purpose: the
# separator is part of the recorded value and must not drift between versions.
REASON_SEPARATOR = "; "


def reason(lang: str, key: str, *args) -> str:
    """Render one reason template in ``lang`` (``"zh"`` or ``"en"``)."""
    return REASON[key][lang] % args if args else REASON[key][lang]


def join_reasons(lang: str, keys: list[tuple[str, tuple]]) -> str:
    """Render and join a list of ``(template_key, args)`` pairs."""
    return REASON_SEPARATOR.join(reason(lang, k, *a) for k, a in keys)


