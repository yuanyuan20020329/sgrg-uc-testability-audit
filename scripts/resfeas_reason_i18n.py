"""Bilingual free-text strings for the Part D resource-feasibility tables.

Why this module exists
----------------------
The audit tables are cited by an English-language Data Descriptor, and the reviewers
read the deposited payload itself. In v1.0.0 the per-row ``reason`` column of
``partD_resfeas_ledger.tsv`` was written in Chinese, and so were the field glossary
(``metric_definitions``), the ``caveat`` note of ``partD_resfeas_libwide_summary.json``
and one example string in ``partD_resfeas_verdict.json``. A schema alone cannot fix
that: a data reviewer must be able to read *why a given resource failed* without a
translation layer.

So the generators now emit English, and both languages are kept here. Keeping the
Chinese originals in the repository makes the v1.0.1 change auditable: the mapping
can be re-derived, re-applied idempotently, and checked row by row against the frozen
v1.0.0 payload (see ``scripts/i18n_normalise_reason.py`` and
``scripts/test_language_normalisation.py``).

What v1.0.1 changed — and what it did NOT
-----------------------------------------
Changed: these strings only.
Unchanged: field names, table structure and column order, the four gates
(``G1_mRNA``, ``G2_UC``, ``G3_powered_control``, ``G4_in_vivo``), ``USABLE``, every
numeric value, and the row order of every table.

A note on ``nan``
-----------------
Some rows carry the literal token ``nan`` (e.g. the ``disease`` column of GSE282444),
which is a stringified missing value produced by the upstream CSV read. The English
translation reproduces it verbatim rather than silently rewriting it, because v1.0.1 is
a language normalisation and must not change a recorded value. Cleaning the token is a
content change and belongs to a later version.
"""
